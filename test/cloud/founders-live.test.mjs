import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {initializeApp,deleteApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {FirestoreNarrativeSessions} from '../../cloud/founders-live-store.ts';
import {foundersPreview} from '../../server/founders-catalog.ts';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw new Error('Firestore Emulator required');
const app=initializeApp({projectId:'demo-le-pacte'},'founders-play-'+randomBytes(6).toString('hex'));
const db=getFirestore(app,'le-pacte'),sessions=new FirestoreNarrativeSessions(db);
after(async()=>{await db.terminate();await deleteApp(app);});
test('Firestore narrative : jeu et secrets persistent, transactions anti-double et révocation',async()=>{
 const now=Date.now(),code='N'+randomBytes(4).toString('hex').toUpperCase();
 const ownerId='owner-'+randomBytes(8).toString('hex');
 const preview=foundersPreview({scenarioId:'fondateurs-hot-spring-demo',skinId:'western',members:[5,6,7,8,9,10]});
 const created=await sessions.create({ownerId,preview,code,title:'Test narratif cloud',now});
 assert.equal(created.access.length,6);
 const pub=await sessions.view(created.id,{role:'public'},now);
 assert.equal(pub.familyGoals,undefined);assert.equal(pub.source,undefined);
 const token=created.access.find(x=>x.family==='A').token;
 const actor=await sessions.authenticate(created.id,token,now);
 assert.equal(actor.family,'A');
 assert.equal((await sessions.view(created.id,actor,now)).self.power,8);
 const org={role:'organizer',id:ownerId};
 const first=await sessions.command(created.id,org,{kind:'start',expectedRevision:0},now+1);
 assert.equal(first.phase,'COUNCIL');
 const command={kind:'vote',expectedRevision:1,data:{kind:'pour',amount:1}};
 const attempts=await Promise.allSettled([sessions.command(created.id,actor,command,now+2),sessions.command(created.id,actor,command,now+2)]);
 assert.equal(attempts.filter(a=>a.status==='fulfilled').length,1);
 assert.equal(attempts.filter(a=>a.status==='rejected').length,1);
 const current=await sessions.view(created.id,actor,now+3);
 assert.equal(current.self.power,7);assert.equal(current.self.bid,1);
 const changed=await sessions.rotate(created.id,'A',ownerId,now+4);
 await assert.rejects(sessions.view(created.id,actor,now+5),/révoqué/);
 const fresh=await sessions.authenticate(created.id,changed.token,now+5);
 assert.equal((await sessions.view(created.id,fresh,now+5)).self.bid,1);
 await assert.rejects(sessions.view(created.id,{role:'organizer',id:'other-owner'},now+5),/refusé/);
 const list=await sessions.list(ownerId),none=await sessions.list('other-owner');
 assert.equal(list.some(x=>x.id===created.id),true);assert.equal(none.some(x=>x.id===created.id),false);
});
