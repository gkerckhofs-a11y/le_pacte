import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DatabaseSync} from 'node:sqlite';
import {foundersPreview} from '../server/founders-catalog.ts';
import {createNarrativeSession,applyNarrativeCommand,narrativePublicView,narrativeFamilyView,narrativeOrganizerView} from '../src/founders-live.ts';
import {LocalNarrativeSessions} from '../server/founders-live-store.ts';

const now=2000000;
const preview=()=>foundersPreview({scenarioId:'fondateurs-hot-spring-demo',skinId:'western',members:[5,6,7,8,9,10]});
const make=()=>createNarrativeSession(preview(),{id:'123456789012123456789012',ownerId:'local-organizer',code:'TEST01',title:'Hot Spring — test',now});
const organizer={role:'organizer',id:'local-organizer'};
const team=id=>({role:'team',family:id});
const run=(s,actor,kind,data={})=>applyNarrativeCommand(s,actor,{kind,data,expectedRevision:s.revision},now+s.revision+1);
test('Session narrative : initialisation, six familles, objectifs confidentiels et ville publique',()=>{
 const s=make();
 assert.equal(s.phase,'READY');
 assert.equal(s.game.families.F.members,10);
 const a=narrativeFamilyView(s,'A'),b=narrativeFamilyView(s,'B');
 assert.notEqual(a.self.objective,b.self.objective);
 assert.equal(a.self.dollars,10);
 assert.equal(a.self.power,8);
 const pub=narrativePublicView(s),serialize=JSON.stringify(pub);
 assert.equal(serialize.includes('Objectif de test'),false);
 assert.equal(serialize.includes('"outcomes"'),false);
 assert.equal(serialize.includes('"source"'),false);
 assert.equal(serialize.includes('D02'),false);
 assert.equal(pub.families.length,6);
 const admin=narrativeOrganizerView(s);
 assert.equal(admin.familyGoals.A,a.self.objective);
 assert.equal(admin.scenario.dilemmas.length,10);
});
test('Vote complet à six familles → résultat réservé à la régie → révélation → branche suivante',()=>{
 let s=run(make(),organizer,'start');
 assert.equal(s.phase,'COUNCIL');assert.equal(s.game.vote.turn,'A');
 const actions=[['A','pour',1],['B','contre',1],['C','contre',1],['D','contre',1],['E','contre',1],['F','contre',1]];
 for(const [family,kind,amount] of actions)s=run(s,team(family),'vote',{kind,amount});
 assert.equal(s.game.vote?.phase,'await_leader');
 s=run(s,team('F'),'chooseLeader',{family:'B'});
 assert.equal(s.phase,'AWAITING_REVEAL');
 assert.equal(narrativePublicView(s).reveal,null);
 assert.equal(narrativePublicView(s).dilemma.title,'Le monopole du chemin de fer');
 assert.throws(()=>run(s,team('A'),'reveal'),/Régie/);
 s=run(s,organizer,'reveal');
 assert.equal(s.phase,'REVEALED');
 assert.equal(s.lastReveal.winner,'contre');
 assert.equal(s.lastReveal.nextId,'D03');
 assert.equal(s.game.city.economie,4);
 assert.equal(s.game.city.developpement,4);
 assert.equal(s.game.city.satisfaction,6);
 assert.equal(narrativePublicView(s).history.length,1);
 s=run(s,organizer,'next');
 assert.equal(s.phase,'COUNCIL');
 assert.equal(s.currentDilemmaId,'D03');
 assert.equal(s.game.vote.id,'D03');
 assert.equal(narrativePublicView(s).reveal,null);
 assert.equal(s.game.history.length,1);
});
test('Offres financières : propositions privées, confirmation bilatérale, anti-double transfert',()=>{
 let s=run(make(),organizer,'start');
 const id='trade_123456789';
 s=run(s,team('A'),'offer',{id,to:'B',amount:3,reason:'Soutien au rail'});
 const p=narrativePublicView(s);
 assert.equal(JSON.stringify(p).includes('Soutien au rail'),false);
 assert.equal(narrativeFamilyView(s,'C').offers.length,0);
 assert.equal(narrativeFamilyView(s,'B').offers.length,1);
 assert.throws(()=>run(s,team('C'),'acceptOffer',{id}),/destinée/);
 s=run(s,team('B'),'acceptOffer',{id});
 assert.equal(s.game.families.A.dollars,7);
 assert.equal(s.game.families.B.dollars,13);
 assert.throws(()=>run(s,team('B'),'acceptOffer',{id}),/destinée/);
 assert.equal(s.game.transactions.length,1);
});
test('Erreurs de permissions, vieux numéro de révision et capacité d’influence',()=>{
 let s=make();
 assert.throws(()=>run(s,team('A'),'start'),/Régie/);
 assert.throws(()=>run(s,{role:'organizer',id:'other'},'start'),/Accès régie/);
 s=run(s,organizer,'start');
 const stale=s.revision;s=run(s,team('A'),'vote',{kind:'pour',amount:1});
 assert.throws(()=>applyNarrativeCommand(s,team('B'),{kind:'vote',expectedRevision:stale,data:{kind:'contre',amount:1}},now),/Révision périmée/);
 assert.throws(()=>run(s,team('B'),'vote',{kind:'contre',amount:500}),/Mise invalide/);
});
test('SQLite : sauvegarde redémarrable, accès famille révocable, accès public sans secrets',()=>{
 const dir=mkdtempSync(join(tmpdir(),'founders-live-')),path=join(dir,'live.sqlite');
 let db;
 try{
  db=new DatabaseSync(path);let store=new LocalNarrativeSessions(db);
  const config=preview();
  const result=store.create({ownerId:'local-organizer',preview:config,code:'LIVE01',title:'Partie test',now});
  assert.equal(result.access.length,6);
  const a=result.access[0],actor=store.authenticate(result.id,a.token,now);
  const before=store.view(result.id,{role:'public'},now);
  assert.equal(before.familyGoals,undefined);
  const family=store.view(result.id,actor,now);
  assert.equal(family.self.id,'A');
  const started=store.command(result.id,organizer,{kind:'start',expectedRevision:0},now+1);
  assert.equal(started.phase,'COUNCIL');
  const rotated=store.rotate(result.id,'A','local-organizer',now+2);
  assert.throws(()=>store.authenticate(result.id,a.token,now+3),/révoqué/);
  assert.equal(store.authenticate(result.id,rotated.token,now+3).family,'A');
  db.close();db=new DatabaseSync(path);store=new LocalNarrativeSessions(db);
  assert.equal(store.view(result.id,{role:'public'},now+3).phase,'COUNCIL');
  assert.throws(()=>store.view(result.id,{role:'organizer',id:'other'},now+3),/Accès organisateur/);
 }finally{db?.close();rmSync(dir,{recursive:true,force:true});}
});
